export function mergeMessages(partial?: Partial<Messages>): Messages {
  if (!partial) return defaultMessages;
  return {
    ...defaultMessages,
    ...partial,
    operators: { ...defaultMessages.operators, ...(partial.operators ?? {}) },
  };
}
